def main() -> None:
    quotes = []
    for text, author in RUSSIAN_SCIENTISTS:
        quotes.append({"text": text, "author": author, "category": "russian"})
    for text, author in FOREIGN_SCIENTISTS:
        quotes.append({"text": text, "author": author, "category": "foreign"})
    for text, author in PHILOSOPHERS:
        quotes.append({"text": text, "author": author, "category": "philosophy"})
    for text, author in WORK_AND_PERSEVERANCE:
        quotes.append({"text": text, "author": author, "category": "work"})

    output = {"version": "1.0", "quotes": quotes}

    here = Path(__file__).resolve().parent
    parser_dir = here.parent
    project_root = parser_dir.parent

    out_parser = parser_dir / "quotes.json"
    out_assets = project_root / "android" / "app" / "src" / "main" / "assets" / "quotes.json"

    out_parser.write_text(
        json.dumps(output, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    out_assets.parent.mkdir(parents=True, exist_ok=True)
    out_assets.write_text(
        json.dumps(output, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    print(f"Wrote {len(quotes)} quotes:")
    print(f"  russian:    {len(RUSSIAN_SCIENTISTS)}")
    print(f"  foreign:    {len(FOREIGN_SCIENTISTS)}")
    print(f"  philosophy: {len(PHILOSOPHERS)}")
    print(f"  work:       {len(WORK_AND_PERSEVERANCE)}")
    print(f"  parser/quotes.json: {out_parser}")
    print(f"  android assets:     {out_assets}")


if __name__ == "__main__":
    main()
